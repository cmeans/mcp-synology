#!/usr/bin/env python3
"""Generate File Station's table of Unicode standardized variation sequences (#515).

A new name may hold VS1-VS7 (U+FE00-FE06) only in a sequence Unicode registers in
StandardizedVariants.txt; anywhere else the selector draws nothing and hides a value.
This script turns that file into
`src/mcp_synology/modules/filestation/standardized_variants.py`.

Usage:
    curl -o StandardizedVariants.txt \\
        https://www.unicode.org/Public/UCD/latest/ucd/StandardizedVariants.txt
    python scripts/gen_standardized_variants.py StandardizedVariants.txt

Regenerate when Unicode publishes a new version, with the `regex` floor in
pyproject.toml (see docs/specs/project-scaffolding-spec.md). Stdlib only.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
OUTPUT = REPO_ROOT / "src/mcp_synology/modules/filestation/standardized_variants.py"
_LINE = re.compile(r"\s*([0-9A-F]{4,6})\s+([0-9A-F]{4,6})\s*;")


def parse(text: str) -> tuple[str, dict[int, list[int]]]:
    """The file's version line and, per VS1-VS7 selector, its registered bases."""
    version = next((line[2:].strip() for line in text.splitlines() if line.startswith("# S")), "")
    bases: dict[int, list[int]] = {}
    for line in text.splitlines():
        match = _LINE.match(line.split("#", 1)[0])
        if match:
            base, selector = int(match.group(1), 16), int(match.group(2), 16)
            if 0xFE00 <= selector <= 0xFE06:
                bases.setdefault(selector, []).append(base)
    return version, bases


def render(version: str, bases: dict[int, list[int]]) -> str:
    lines = [
        '"""Unicode standardized variation sequences for VS1-VS7 (#515).',
        "",
        f"Generated by scripts/gen_standardized_variants.py from {version}.",
        'Don\'t edit by hand."""',
        "",
        "from __future__ import annotations",
        "",
        "# Per selector, the characters it's registered after.",
        "# fmt: off",
        "STANDARDIZED_BASES: dict[str, frozenset[str]] = {",
    ]
    for selector in sorted(bases):
        lines.append(f'    "\\u{selector:04x}": frozenset(map(chr, (')
        codes = [f"0x{b:04X}," for b in sorted(set(bases[selector]))]
        for i in range(0, len(codes), 10):
            lines.append("        " + " ".join(codes[i : i + 10]))
        lines.append("    ))),")
    lines.append("}")
    lines.append("# fmt: on")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("source", type=Path, help="StandardizedVariants.txt")
    args = parser.parse_args()
    version, bases = parse(args.source.read_text(encoding="utf-8"))
    OUTPUT.write_text(render(version, bases), encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(REPO_ROOT)} ({sum(map(len, bases.values()))} sequences)")


if __name__ == "__main__":
    main()
