#!/usr/bin/env python3
"""Generate File Station's tables of Unicode's registered variation sequences (#515).

A new name may hold VS1-VS7 (U+FE00-FE06) only in a sequence StandardizedVariants.txt
registers, and VS15/VS16 (U+FE0E/FE0F) only after an emoji emoji-variation-sequences.txt
registers; anywhere else the selector draws nothing and hides a value. This script turns
those two files into `src/mcp_synology/core/standardized_variants.py`.

Usage, with X.Y.Z the Unicode version of the `regex` floor's data (not `latest`, which can
be newer than the property data the checks use). `regex` doesn't report it: its release
notes name it, and the header of `standardized_variants.py` records the one in use:
    curl -O https://www.unicode.org/Public/X.Y.Z/ucd/StandardizedVariants.txt
    curl -O https://www.unicode.org/Public/X.Y.Z/ucd/emoji/emoji-variation-sequences.txt
    python scripts/gen_standardized_variants.py StandardizedVariants.txt \\
        emoji-variation-sequences.txt

Regenerate when the `regex` floor in pyproject.toml moves to a new Unicode version,
together with `scripts/gen_decompositions.py` (see docs/specs/project-scaffolding-spec.md).
Stdlib only.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
OUTPUT = REPO_ROOT / "src/mcp_synology/core/standardized_variants.py"
_LINE = re.compile(r"\s*([0-9A-F]{4,6})\s+([0-9A-F]{4,6})\s*;")


def parse(text: str, selectors: range) -> tuple[str, dict[int, set[int]]]:
    """The file's first line and, per selector in ``selectors``, its registered bases."""
    lines = text.splitlines()
    version = lines[0].lstrip("# ").strip() if lines else ""
    stated = next((line[11:].strip() for line in lines if line.startswith("# Version: ")), "")
    if stated and stated not in version:
        version = f"{version} {stated}"
    bases: dict[int, set[int]] = {}
    for line in text.splitlines():
        match = _LINE.match(line.split("#", 1)[0])
        if match:
            base, selector = int(match.group(1), 16), int(match.group(2), 16)
            if selector in selectors:
                bases.setdefault(selector, set()).add(base)
    return version, bases


def _codes(values: set[int]) -> list[str]:
    codes = [f"0x{b:04X}," for b in sorted(values)]
    return ["        " + " ".join(codes[i : i + 10]) for i in range(0, len(codes), 10)]


def render(
    standardized_version: str,
    standardized: dict[int, set[int]],
    emoji_version: str,
    emoji: dict[int, set[int]],
) -> str:
    lines = [
        '"""Unicode\'s registered variation sequences for VS1-VS7 and VS15/VS16 (#515).',
        "",
        "Generated by scripts/gen_standardized_variants.py from",
        f"{standardized_version} and {emoji_version}.",
        'Don\'t edit by hand."""',
        "",
        "from __future__ import annotations",
        "",
        "# fmt: off",
        "# Per VS1-VS7 selector, the characters StandardizedVariants.txt registers it after.",
        "STANDARDIZED_BASES: dict[str, frozenset[str]] = {",
    ]
    for selector in sorted(standardized):
        lines.append(f'    "\\u{selector:04x}": frozenset(map(chr, (')
        lines.extend(_codes(standardized[selector]))
        lines.append("    ))),")
    lines.append("}")
    # Text (VS15) and emoji (VS16) presentation are registered for the same bases.
    emoji_bases = {b for bases in emoji.values() for b in bases if b >= 0x80}
    lines.append("# The emoji emoji-variation-sequences.txt registers VS15/VS16 after (not ASCII).")
    lines.append("EMOJI_VS_BASES: frozenset[str] = frozenset(map(chr, (")
    lines.extend(line[4:] for line in _codes(emoji_bases))
    lines.append(")))")
    lines.append("# fmt: on")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("standardized", type=Path, help="StandardizedVariants.txt")
    parser.add_argument("emoji", type=Path, help="emoji-variation-sequences.txt")
    args = parser.parse_args()
    s_version, standardized = parse(
        args.standardized.read_text(encoding="utf-8"), range(0xFE00, 0xFE07)
    )
    e_version, emoji = parse(args.emoji.read_text(encoding="utf-8"), range(0xFE0E, 0xFE10))
    OUTPUT.write_text(render(s_version, standardized, e_version, emoji), encoding="utf-8")
    count = sum(map(len, standardized.values()))
    print(f"Wrote {OUTPUT.relative_to(REPO_ROOT)} ({count} standardized sequences)")


if __name__ == "__main__":
    main()
