#!/usr/bin/env python3
"""Generate File Station's table of canonical decompositions newer than Python 3.11 (#515).

The repeated-mark check on new names works on each name's NFD. Python 3.11's
`unicodedata` is Unicode 14.0, so it leaves a character assigned later undecomposed where
a newer Python decomposes it (U+16121 is U+1611E twice on 3.14), and a name would pass or
fail by interpreter. Canonical decompositions never change once a character is assigned,
so this script lists those of every character newer than Unicode 14.0, taken from the
same Unicode version as `regex`'s property data, in
`src/mcp_synology/core/decompositions.py`.

Usage, with X.Y.Z the Unicode version of the `regex` floor's data, recorded in the header
of `src/mcp_synology/core/standardized_variants.py` (`regex` doesn't report
it; its release notes name it):
    curl -O https://www.unicode.org/Public/X.Y.Z/ucd/UnicodeData.txt
    curl -O https://www.unicode.org/Public/X.Y.Z/ucd/DerivedAge.txt
    python scripts/gen_decompositions.py UnicodeData.txt DerivedAge.txt

Regenerate with `scripts/gen_standardized_variants.py`, when the `regex` floor in
pyproject.toml moves to a new Unicode version (see docs/specs/project-scaffolding-spec.md).
Stdlib only.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
OUTPUT = REPO_ROOT / "src/mcp_synology/core/decompositions.py"
# Python 3.11's `unicodedata` (requires-python's floor) knows every character to here.
FLOOR_AGE = (14, 0)
_AGE = re.compile(r"([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*(\d+)\.(\d+)")


def parse_ages(text: str) -> tuple[str, dict[int, tuple[int, int]]]:
    """DerivedAge.txt's first line and each listed code point's age."""
    lines = text.splitlines()
    version = lines[0].lstrip("# ").strip() if lines else ""
    ages: dict[int, tuple[int, int]] = {}
    for line in lines:
        match = _AGE.match(line.split("#", 1)[0].strip())
        if match:
            first = int(match.group(1), 16)
            last = int(match.group(2) or match.group(1), 16)
            age = (int(match.group(3)), int(match.group(4)))
            for cp in range(first, last + 1):
                ages[cp] = age
    return version, ages


def parse_decompositions(text: str) -> dict[int, list[int]]:
    """UnicodeData.txt's canonical decompositions (one level; compatibility ones left out)."""
    found: dict[int, list[int]] = {}
    for line in text.splitlines():
        fields = line.split(";")
        if len(fields) > 5 and fields[5] and not fields[5].startswith("<"):
            found[int(fields[0], 16)] = [int(p, 16) for p in fields[5].split()]
    return found


def newer_than_floor(
    decompositions: dict[int, list[int]], ages: dict[int, tuple[int, int]]
) -> dict[int, list[int]]:
    """The decompositions of characters Python 3.11's `unicodedata` doesn't know."""
    return {cp: d for cp, d in decompositions.items() if ages.get(cp, (0, 0)) > FLOOR_AGE}


def render(version: str, data_version: str, table: dict[int, list[int]]) -> str:
    lines = [
        '"""Canonical decompositions of the characters newer than Python 3.11\'s Unicode (#515).',
        "",
        "Generated by scripts/gen_decompositions.py from",
        f"{data_version} and {version}.",
        'Don\'t edit by hand."""',
        "",
        "from __future__ import annotations",
        "",
        "# fmt: off",
        "# One level, as UnicodeData.txt gives them; a part can decompose again.",
        "NEW_DECOMPOSITIONS: dict[str, str] = {",
    ]
    for cp in sorted(table):
        parts = "".join(f"\\U{p:08x}" if p > 0xFFFF else f"\\u{p:04x}" for p in table[cp])
        lines.append(f'    "\\U{cp:08x}": "{parts}",')
    lines.append("}")
    lines.append("# fmt: on")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("unicode_data", type=Path, help="UnicodeData.txt")
    parser.add_argument("derived_age", type=Path, help="DerivedAge.txt")
    args = parser.parse_args()
    version, ages = parse_ages(args.derived_age.read_text(encoding="utf-8"))
    decompositions = parse_decompositions(args.unicode_data.read_text(encoding="utf-8"))
    table = newer_than_floor(decompositions, ages)
    data_version = version.replace("DerivedAge", "UnicodeData")
    OUTPUT.write_text(render(version, data_version, table), encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(REPO_ROOT)} ({len(table)} decompositions)")


if __name__ == "__main__":
    main()
