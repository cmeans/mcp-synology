# Host, HTTPS, port, permission, alias, username, password.
_ANSWERS = "192.168.1.50\nn\n\nread\n\nmy admin\nhunter2\n"


@pytest.mark.usefixtures("no_keyring")
class TestSetupWithNoKeyring:
    def _setup(self, tmp_path: Path) -> tuple[Path, str]:
        config_dir = tmp_path / "config"
        with (
            patch("mcp_synology.cli.setup._CONFIG_DIR", config_dir),
            patch("mcp_synology.core.config.discover_config_path", side_effect=FileNotFoundError),
        ):
            result = CliRunner().invoke(main, ["setup"], input=_ANSWERS)
        assert result.exit_code == 0, result.output
        return config_dir / "192-168-1-50.yaml", result.output

    def test_it_writes_the_config_the_variables_need(self, tmp_path: Path) -> None:
        """QA round 3 on #532: every answer taken, then no file, so `check` found none."""
        written, output = self._setup(tmp_path)
        assert load_config(str(written)).connection is not None
        assert f"test it: mcp-synology check --config {shlex.quote(str(written))}" in output
        # Nothing to log in with yet that the server would use: `check` tests it.
        assert "Connecting to NAS" not in output

    def test_the_password_stays_out_of_the_file_and_the_output(self, tmp_path: Path) -> None:
        written, output = self._setup(tmp_path)
        assert "hunter2" not in written.read_text()
        assert "hunter2" not in output

    def test_the_variables_suit_any_shell_and_quote_the_name(self, tmp_path: Path) -> None:
        _, output = self._setup(tmp_path)
        assert "export " not in output
        assert f"  SYNOLOGY_USERNAME={shlex.quote('my admin')}\n" in output
        assert "  SYNOLOGY_PASSWORD=<your password>\n" in output

    def test_the_client_snippet_sets_them(self, tmp_path: Path) -> None:
        _, output = self._setup(tmp_path)
        snippet = json.loads(output[output.index('{\n  "mcpServers"') :])
        env = snippet["mcpServers"]["synology-192-168-1-50"]["env"]
        assert env["SYNOLOGY_USERNAME"] == "my admin"
        assert env["SYNOLOGY_PASSWORD"] == "<your password>"

    def test_an_existing_config_is_named(self, tmp_path: Path) -> None:
        config = tmp_path / "mynas.yaml"
        config.write_text(
            "schema_version: 1\nconnection:\n  host: 192.168.1.50\n"
            "modules:\n  filestation:\n    enabled: true\n"
        )
        result = CliRunner().invoke(main, ["setup", "--config", str(config)], input="me\nhunter2\n")
        assert result.exit_code == 0, result.output
        assert f"test it: mcp-synology check --config {shlex.quote(str(config))}" in result.output


@pytest.mark.usefixtures("no_keyring")
class TestTwoFactorWithNoKeyring:
    """`setup` can't keep a token here and never prints one, so naming it alone went in a
    circle (#481)."""

    SOURCES = {"username": "env", "password": "env", "device_id": None}

    @pytest.mark.parametrize("code", [403, 404])
    def test_the_advice_names_the_variable(self, code: int) -> None:
        advice = refusal_advice(code, "", self.SOURCES, cli=True)
        assert advice == NO_KEYRING_2FA_ADVICE
        assert "SYNOLOGY_DEVICE_ID" in advice
        assert "keyring get mcp-synology/<instance_id> device_id" in advice

    def test_a_running_server_needs_the_restart(self) -> None:
        advice = refusal_advice(403, "", self.SOURCES)
        assert advice.endswith(" and restart the server")

    def test_a_rejected_token_says_where_it_came_from(self) -> None:
        sources = {**self.SOURCES, "device_id": "SYNOLOGY_DEVICE_ID in this shell"}
        advice = refusal_advice(403, "", sources, cli=True)
        assert advice.startswith("The device token comes from SYNOLOGY_DEVICE_ID in this shell.")
        assert "remove it" not in advice

    def test_setup_says_it_up_front(self, tmp_path: Path) -> None:
        config_dir = tmp_path / "config"
        with (
            patch("mcp_synology.cli.setup._CONFIG_DIR", config_dir),
            patch("mcp_synology.core.config.discover_config_path", side_effect=FileNotFoundError),
        ):
            result = CliRunner().invoke(main, ["setup"], input=_ANSWERS)
        assert f"If this account uses 2FA: {NO_KEYRING_2FA_ADVICE}." in result.output


def test_a_keyring_keeps_the_usual_advice(no_keyring: None) -> None:
    previous = keyring.get_keyring()
    keyring.set_keyring(MemoryKeyring())
    try:
        advice = refusal_advice(
            403, "", {"username": KEYRING, "password": KEYRING, "device_id": None}, cli=True
        )
    finally:
        keyring.set_keyring(previous)
    assert advice.startswith("Run 'mcp-synology setup --config <your config file>'")
    assert "SYNOLOGY_DEVICE_ID" not in advice


def test_no_config_says_setup_makes_one(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """The wheel holds no `examples/`, and the message never named `setup` (pre-QA on #541)."""
    monkeypatch.chdir(tmp_path)
    monkeypatch.delenv("MCP_SYNOLOGY_CONFIG", raising=False)
    with (
        patch("mcp_synology.core.config.Path.home", return_value=tmp_path),
        pytest.raises(FileNotFoundError) as exc,
    ):
        discover_config_path()
    assert "Run 'mcp-synology setup' to create one" in str(exc.value)
    assert "examples/" not in str(exc.value)
