SRC = Path(mcp_synology.__file__).parent
BARE = re.compile(r"mcp-synology (setup|check)\b(?! --config)")
# Where the bare form is right: the constants for no config file, and a file's header comment.
ALLOWED = {
    "'mcp-synology setup'",
    "'mcp-synology check'",
    "# Generated by mcp-synology setup\n",
}


def _docstrings(tree: ast.AST) -> set[ast.AST]:
    found: set[ast.AST] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Module | ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef):
            first = node.body[0] if node.body else None
            if isinstance(first, ast.Expr) and isinstance(first.value, ast.Constant):
                found.add(first.value)
    return found


def _bare_in_source(source: str) -> list[str]:
    tree = ast.parse(source)
    docstrings = _docstrings(tree)
    return [
        f"{node.lineno}: {node.value!r}"
        for node in ast.walk(tree)
        if isinstance(node, ast.Constant)
        and isinstance(node.value, str)
        and node not in docstrings
        and node.value not in ALLOWED
        and BARE.search(node.value)
    ]


def test_no_message_names_a_bare_command() -> None:
    bare = [
        f"{path.relative_to(SRC)}:{found}"
        for path in sorted(SRC.rglob("*.py"))
        for found in _bare_in_source(path.read_text(encoding="utf-8"))
    ]
    bare += [
        f"{path.relative_to(SRC)}: {line}"
        for path in sorted(SRC.rglob("*.md"))
        for line in path.read_text(encoding="utf-8").splitlines()
        if BARE.search(line)
    ]
    assert bare == []


def test_the_scan_finds_one_in_a_message_and_skips_a_docstring() -> None:
    source = (
        'def f():\n    """Run mcp-synology check."""\n'
        "    x = 1\n"
        "    return f\"Run 'mcp-synology setup' on {x}\"\n"
    )
    found = _bare_in_source(source)
    assert len(found) == 1
    assert "mcp-synology setup" in found[0]


def test_the_guard_sees_a_bare_command() -> None:
    assert BARE.search("Run 'mcp-synology check' to verify")
    assert BARE.search("(mcp-synology setup)")
    assert not BARE.search("Run 'mcp-synology check --config <your config file>'")


